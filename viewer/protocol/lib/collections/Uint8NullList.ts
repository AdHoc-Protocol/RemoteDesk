/**
 * A specialized list for storing `number` values with support for an `UNDEFINED` state to represent
 * missing or uninitialized elements.
 *
 * ## Why this class exists
 *
 * Consider a field whose value domain saturates the underlying type — every bit pattern in a
 * `uint64` (or `uint8`, `uint16`, ...) is a real data value — *and* the application also needs
 * a "null / missing" marker. There is no spare sentinel left inside the value type. The
 * conventional escape is to widen the storage: pair each value with a separate `bool`, or move
 * to a wider numeric type. Either way the per-element footprint roughly **doubles**:
 *
 *     u64 + null  →  16 B / slot  (8 B value + 8 B for bool/padding/tag)
 *     u32 + null  →   8 B / slot
 *     u16 + null  →   4 B / slot
 *      u8 + null  →   2 B / slot
 *
 * `Uint8NullList` (and its generated sister types `Int8NullList`, …, `Float64NullList`)
 * sidesteps the widening tax by storing the value in its natural width and pushing the
 * nullness into a **side-channel bitmap** — one bit per logical slot:
 *
 *     u64 + null  →  ~8.125 B / slot  (≈ 49 % saved vs the widened form)
 *     u32 + null  →  ~4.125 B / slot  (≈ 48 % saved)
 *     u16 + null  →  ~2.125 B / slot  (≈ 47 % saved)
 *      u8 + null  →  ~1.125 B / slot  (≈ 44 % saved)
 *
 * The savings come specifically from the saturated-domain case. If the value type already has
 * spare bit patterns the application can use as null, you don't need this class — pick a
 * sentinel and use {@link Uint8List} directly.
 *
 * ## Storage strategies (layered on top)
 *
 * The class uses a {@link BitList.RW} to track nullity (whether an element is `UNDEFINED`) and
 * a {@link Uint8Array} to store non-`UNDEFINED` `number` values. It dynamically switches
 * between two layouts based on the density of non-`UNDEFINED` elements vs a configurable
 * threshold:
 *
 * - **Compressed Strategy**: `values` packs only the non-`UNDEFINED` entries contiguously;
 *   element access goes through `nulls.rank(index)`. Cheaper memory; one extra rank lookup
 *   per read. Wins when most slots are null.
 * - **Flat Strategy**: `values[i]` mirrors logical position `i` (the slot is meaningful only
 *   when `nulls.get(i)` is true). O(1) access, but pays memory for the unused slots. Wins
 *   when most slots have values.
 *
 * The strategy switch is automatic — see {@link RW.flatStrategyThreshold}.
 *
 * Value searches use SameValueZero (as `Array.prototype.includes` and `Set`): `NaN` finds `NaN`, `-0` matches `0`.
 * A written value is stored as UNDEFINED when it, or its `Uint8Array`-converted form, equals `undefinedValue` (SameValueZero).
 *
 * @example
 * ```typescript
 * const list = new Uint8NullList.RW(-10);   // capacity hint of 10, size 0
 * list.append(1).append(undefined).append(2);
 * console.log(list.toJSON());    // [1, undefined, 2]
 * console.log(list.cardinality); // 2 (two non-UNDEFINED values)
 * ```
 *
 * @namespace
 */
