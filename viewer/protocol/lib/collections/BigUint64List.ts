    /**
     * SameValueZero (as `Array.prototype.includes` and `Set`): `NaN` equals `NaN`, `-0` equals `0`.
     * @private
     */
    function sameValueZero(a: bigint, b: bigint): boolean {
        return a === b || (a !== a && b !== b);
    }

    /**
     * Copies `len` items of `src` from `si` on into `dst` at `at`: one `set` for a typed source (no temporary copy) or a
     * whole plain array, an element loop otherwise. A source sharing `dst`'s buffer is safe: `set` copies it first.
     * @private
     */
    function copyIn(dst: BigUint64Array, at: number, src: ArrayLike<bigint>, si: number, len: number): void {
        if (ArrayBuffer.isView(src) && typeof (src as any).subarray === "function") dst.set((src as BigUint64Array).subarray(si, si + len), at);
        else if (si === 0 && len === src.length) dst.set(src, at);
        else for (let i = 0; i < len; i++) dst[at + i] = src[si + i];
    }

