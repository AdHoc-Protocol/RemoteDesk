    /**
     * The host of a set of TCP connections - a {@link TCP.Server} or a {@link TCP.Client} - and what they share: the
     * registry of connection slots, the parked sessions, the options, and the {@link TCP.Engine} whose timers the
     * connections run on.
     */
    export abstract class TCP {
        /** The registry of all allocated connections. It only grows: O(1) access by slot index. */
        readonly connections: TCP.ExternalConnection[] = [];

        /** How many connections hold a socket right now. Transport-internal: written by the connections themselves. */
        live = 0;

        /** @return how many connections of this host hold a socket right now. */
        connections_live(): number { return this.live; }

        /** @return how many connection slots this host has ever made - the high-water mark of them all. */
        connections_size(): number { return this.connections.length; }

        /**
         * Counts the slots by state into `into`, indexed by the state itself: FREE 0, ACTIVE 1, CLEANING 2, PARKED 3.
         */
        census(into: number[] = [0, 0, 0, 0]): number[] {
            into[0] = into[1] = into[2] = into[3] = 0;
            for (const connection of this.connections) into[connection.state]++;
            return into;
        }

        /** @return the census as text, for a log line: "free 12, active 300, cleaning 0, parked 4, slots 316". */
        censusText(): string {
            const n = this.census();
            return `free ${n[0]}, active ${n[1]}, cleaning ${n[2]}, parked ${n[3]}, slots ${this.connections.length}`;
        }

        /** The timers this host's connections run on, possibly shared with other hosts. */
        readonly engine: TCP.Engine;

        /**
         * Parked sessions, sorted ascending by their {@link TCP.ExternalConnection.resumable} deadline and linked through
         * the same `next` the free list uses (a slot is on one of the two, or active). Doubly linked here: a park walks
         * in from the tail - most sessions share the same wait - and a reclaim unlinks in O(1).
         */
        protected parked_head?: TCP.ExternalConnection | undefined;
        protected parked_tail?: TCP.ExternalConnection | undefined;
        private reapTimer?: Cancel | undefined;
        private reapAt = 0;

        /**
         * Claims the parked session of `session_id`: taken off the parked list and returned FREE, keeping its Internal
         * and holding no socket. Numeric tokens alone are NOT authentication.
         *
         * @return the slot, FREE and off the list, or `undefined`.
         */
        parked(session_id: number): TCP.ExternalConnection | undefined {
            if (!Number.isSafeInteger(session_id) || session_id < 0) return undefined;
            const c = this.connections[Math.floor(session_id / 4294967296)];
            if (c === undefined || c.state !== TCP.ExternalConnection.PARKED || c.id !== (session_id | 0)) return undefined;
            this.unpark(c);
            c.state = TCP.ExternalConnection.FREE;
            return c;
        }

        /** Puts a lost session on the parked list, sorted by its deadline. A timer ends it when the wait runs out. */
        parkConnection(con: TCP.ExternalConnection): void {
            con.state = TCP.ExternalConnection.PARKED;
            let p = this.parked_tail;
            while (p !== undefined && con.resumable < p.resumable) p = p.prev;
            con.prev = p;
            con.next = p === undefined ? this.parked_head : p.next;
            if (con.next === undefined) this.parked_tail = con; else con.next.prev = con;
            if (p === undefined) this.parked_head = con; else p.next = con;
            this.scheduleReap();
        }

        private unpark(c: TCP.ExternalConnection): void {
            if (c.prev === undefined) this.parked_head = c.next; else c.prev.next = c.next;
            if (c.next === undefined) this.parked_tail = c.prev; else c.next.prev = c.prev;
            c.prev = c.next = undefined;
        }

        /** Retrieves a connection by its slot index in O(1); only an active one. */
        getConnection(index: number): TCP.ExternalConnection | undefined {
            const con = this.connections[index];
            return con?.isActive() ? con : undefined;
        }

        /**
         * Ends the parked sessions whose wait has run out. The list is sorted by deadline, so the walk ends at the first
         * session still waiting. Run by the host's one timer, set for the head of the list.
         */
        reapParked(): void {
            const now = this.engine.seconds();
            for (let c = this.parked_head; c !== undefined && c.resumable <= now; c = this.parked_head) {
                this.unpark(c);
                c.state = TCP.ExternalConnection.CLEANING;
                c.reap();
            }
            this.scheduleReap();
        }

        private scheduleReap(): void {
            const head = this.parked_head;
            if (head === undefined || this.stopped) {
                this.reapTimer?.();
                this.reapTimer = undefined;
                return;
            }
            if (this.reapTimer !== undefined && this.reapAt <= head.resumable) return;
            this.reapTimer?.();
            this.reapAt = head.resumable;
            this.reapTimer = this.engine.schedule(() => {
                this.reapTimer = undefined;
                this.reapParked();
            }, delay(head.resumable * 1000 - this.engine.now()), true);
        }

//#region the restart of the process
        /**
         * The process ends, and the sessions of this host go on in the next one ( {@link restore} ). They live in their files as
         * they go ( {@link AdHoc.Connection.Control} ): a process that falls leaves them there too. A clean end adds what a fall
         * cannot: every session whose peer is identified is made to wait for it, as after a loss, what its transmitter holds goes
         * into its journal, and its files go to the disk, closed cleanly - the next process takes them up whatever happens to the
         * system meanwhile. A session whose Internal does not take it along ( `save` absent or `false` ) ends with the process.
         * For the peers the sockets are lost: they dial again, into the next process. One thread: the sessions park here and now.
         * Java's `TCP.stop( wait_ms )`; {@link stop} here is the engine closing.
         *
         * @return how many sessions were closed cleanly.
         */
        stopSessions(): number {
            this.deafen(); //no peer comes back into this process: what it would take after the stop the next process would not know
            for (const c of this.connections)
                if (c.isActive() && c.id !== 0) c.lost(); //as a loss: the session parks - the teardown runs here and now
            let closed = 0;
            for (let c = this.parked_head; c !== undefined; c = c.next) {
                const internal = c.Internal as AdHoc.Connection.Internal | undefined;
                if (internal === undefined || (internal as unknown) === c) continue;
                const r = internal.BytesDst;
                const control = r instanceof AdHoc.Connection.Receiver ? r.control : undefined;
                if (control === undefined) continue;
                control.stop();
                closed++;
            }
            return closed;
        }

        /**
         * The sessions of hosts the process before left in {@link AdHoc.Connection.Transmitter.Resumable.dir} - it ended or it
         * fell - go on in this one: each takes a slot of its own, parked for the rest of its wait ( counted from when it was parked,
         * or from now for one that had its socket when the process fell ), with the account it had, an Internal `internals` makes
         * for the connection it is of, and what that Internal appended of itself ( {@link AdHoc.Connection.Internal.load} ): its
         * journal and the position of its receiver as they were. A peer that dials again reclaims it as after any loss - by the
         * token of the slot ( {@link TCP.ExternalConnection.session} ), which the application learns from the slots returned.
         * Before the host takes callers. A session whose wait ran out meanwhile, or that its Internal did not take along, is
         * deleted. A browser has no files: nothing is restored there.
         *
         * @return the slots of the sessions that go on.
         */
        restore(internals: (kind: number) => AdHoc.Connection.Internal | undefined): TCP.ExternalConnection[] {
            const restored: TCP.ExternalConnection[] = [];
            const C = AdHoc.Connection.Control,
                R = AdHoc.Connection.Transmitter.Resumable;
            if (!R.in_files()) return restored;
            for (const name of C.heads()) {
                const h = C.peek(R.dir + "/" + name + ".head");
                if (h !== undefined && (C.word(h, C.H_FLAGS, 4) & C.HOST) === 0) continue; //the application takes it up ( Control.open )
                const meta = h === undefined ? -1 : C.meta(h);
                const fresh = meta < 0 ? undefined : internals(C.word(h!, C.H_KIND, 4));
                if (fresh === undefined) {
                    C.delete(name);
                    continue;
                }
                const parked = C.word(h!, C.H_PARKED, 8);
                let deadline: number;
                try {
                    deadline = (parked === 0 ? R.now() : parked) + (fresh.resumable_seconds?.(undefined!, Event.REMOTE_CLOSE_GRACEFUL) ?? 0);
                } catch (_) {
                    deadline = 0;
                }
                if (R.expired(deadline)) {
                    fresh.External?.(undefined);
                    C.delete(name);
                    continue;
                }
                const id = C.word(h!, C.H_ID, 4);
                const saved = C.saved(h!, meta);
                if (this.connections.length >= 2097152) throw new RangeError("Session tokens exhausted their safe integer range");
                const con = this.new_connection(this);
                con.index = this.connections.length;
                this.connections.push(con);
                con.Internal = fresh;
                fresh.External?.(con);
                con.id = id;
                con.resumable = deadline;
                fresh.load?.(saved);
                this.parkConnection(con);
                restored.push(con);
            }
            return restored;
        }
//#endregion

        /** The free list: slots waiting for their next session. */
        protected free_head?: TCP.ExternalConnection | undefined;

        /**
         * Puts a slot on the free list. {@link TCP.Client} overrides this: a client owns one connection and re-arms it in
         * place.
         */
        free(con: TCP.ExternalConnection): void {
            con.state = TCP.ExternalConnection.FREE;
            con.next = this.free_head;
            this.free_head = con;
        }

        /** A factory for the connections of this host: {@link TCP.ExternalConnection}, {@link TCP.WebSocket}, a subclass. */
        readonly new_connection: (host: TCP) => TCP.ExternalConnection;

        /** A name for logs. */
        readonly name: string;

        /**
         * How long the wait for the peer's answer to our close lasts, in milliseconds. A policy of the host: it bounds
         * the post-close linger independently of the receive timeout, which may legitimately be minutes.
         */
        lingerTimeout: number;

        /** A connection of `address` is gone. Only a {@link TCP.Server} with a per-address limit counts anything. */
        release(_address: string): void { }

        readonly options: ResolvedOptions;

        /** The handler of otherwise unhandled failures. */
        readonly onFailure: (source: unknown, error: Error) => void;

        /**
         * @param options or, as Java's TCP(name, new_connection, onFailure, buffer_size) and the former TS Host take it,
         *                the buffer size alone.
         */
        constructor(name: string, new_connection: (host: TCP) => TCP.ExternalConnection,
            onFailure: (source: unknown, error: Error) => void = TCP.onFailurePrintConsole, options: Options | number = {}) {
            if (typeof options === "number") options = {bufferSize: options};
            this.name = name;
            this.new_connection = new_connection;
            this.onFailure = onFailure;
            this.options = {
                bufferSize: options.bufferSize ?? 16384,
                maxPendingBytes: options.maxPendingBytes ?? 1048576,
                transmitBudget: options.transmitBudget ?? 65536,
                mux: options.mux ?? false,
            };
            for (const n of [this.options.bufferSize, this.options.maxPendingBytes, this.options.transmitBudget])
                if (!Number.isSafeInteger(n) || n < 8) throw new RangeError("Byte limits must be safe integers >= 8");
            this.lingerTimeout = options.lingerTimeout ?? 5000;
            this.engine = options.engine ?? new TCP.Engine();
            this.engine.hosts.add(this); //the engine's close ends this host's connections too
        }

        toString(): string { return this.name; }

        /** The transmit buffer size of this host's connections (the former TS Host.buff_size). */
        get buff_size(): number { return this.options.bufferSize; }

        /**
         * Takes a connection for a session: the head of the free list, else a new slot.
         */
        protected allocate(): TCP.ExternalConnection {
            if (this.stopped) throw new Error("TCP has shut down");
            let con = this.free_head;
            if (con !== undefined) {
                this.free_head = con.next;
                con.next = undefined;
            } else {
                if (this.connections.length >= 2097152) throw new RangeError("Session tokens exhausted their safe integer range");
                con = this.new_connection(this);
                con.index = this.connections.length;
                this.connections.push(con); //in the registry before it is activated
            }
            if (!con.activate()) throw new Error("A slot on the free list was not FREE.");
            return con;
        }

        private stopped = false;

        /**
         * Stops, giving the sessions `grace` milliseconds to finish what they were saying - Java shutdown(Duration):
         * nothing new is taken in, every connection is asked to close the polite way, whoever is still there when the
         * grace runs out is torn down, and the engine is closed. Without a grace: at once.
         *
         * @return `true` if every session ended on its own inside the grace.
         */
        shutdown(grace = 0): Promise<boolean> {
            this.deafen();
            if (!(grace > 0)) {
                this.each(false);
                this.engine.close();
                return Promise.resolve(true);
            }
            this.each(true);
            return new Promise(resolve => {
                const until = this.engine.now() + grace;
                const poll = (): void => {
                    const quiet = this.live === 0;
                    if (!quiet && this.engine.now() < until) { this.engine.schedule(poll, 5); return; }
                    this.each(false); //whoever is left
                    this.engine.close();
                    resolve(quiet);
                };
                poll();
            });
        }

        /** Every connection that still holds a socket: closed the polite way, or torn down. */
        private each(politely: boolean): void {
            for (const con of this.connections)
                if (con.isActive()) {
                    if (politely) con.close();
                    else con.abort();
                }
        }

        /** Takes nothing new in. A {@link TCP.Server} refuses further sockets; a client gives up a connect in progress. */
        protected deafen(): void { }

        /** The engine is closing: the connections are torn down, the parked sessions end, no timer is left. */
        stop(): void {
            if (this.stopped) return;
            this.deafen();
            this.each(false);
            this.stopped = true;
            for (let c = this.parked_head; c !== undefined; c = this.parked_head) {
                this.unpark(c);
                c.state = TCP.ExternalConnection.CLEANING;
                c.reap();
            }
            this.scheduleReap();
        }

        /** Reports to {@link onFailure}; a handler that throws must never strand a slot or its timers. */
        report(source: unknown, error: unknown): void {
            try { this.onFailure(source, error instanceof Error ? error : new Error(String(error))); }
            catch { /* swallowed: see above */ }
        }

        static readonly onFailurePrintConsole = (source: unknown, error: Error): void => {
            native.console?.error("onFailure from " + String(source), error);
        };
    }

