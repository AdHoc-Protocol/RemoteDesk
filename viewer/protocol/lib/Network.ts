            private _internal: AdHoc.Connection.Internal | undefined;

            get Internal(): AdHoc.Connection.Internal { return this._internal!; }

            /** TS: `undefined` unseats it - a server slot between sessions holds none. */
            set Internal(internal: AdHoc.Connection.Internal | undefined) { this._internal = internal; }

            /**
             * What the protocol layer seated last declared of Noise ( {@link secure} ), not taken yet: `undefined` - nothing,
             * `REFUSED` - there are no keys for the connection.
             */
            private secured: Chain | undefined;

            /** @internal A dialing connection: the Noise the protocol layer seated for the socket being connected declared; `undefined` - none. */
            declared: Chain | undefined;

            /**
             * For the generated code: the Noise of the socket of this connection, as [Noise] of the description of its protocol declares
             * it ( `Chain.noiseKeys` of Crypto.ts ). The generated `External( ext )` calls it every time the protocol layer is seated - for
             * every socket, before the handshake: as a socket is accepted, before a connect and every reconnect, as a caller of a
             * multiplexed port names its connection. The end that made the connection starts the handshake. Not called - the socket
             * stays as it is. `undefined` - the connection is refused: an accepted one is closed, a dialing one is not dialed, and the
             * failure goes to the host.
             */
            secure(chain: Chain | undefined): void {
                if (chain !== undefined && (chain.tlsHost !== undefined || chain.tlsCert !== undefined || chain.tlsTrust !== undefined))
                    throw new Error("TLS of a connection is chosen by its host or client, not by [Noise]");
                this.secured = chain ?? REFUSED;
            }

            /**
             * Seats `internal` on this connection for a new socket: it learns its connection, and what it declares of Noise
             * ( {@link secure} ) is taken. `undefined` - nothing; `REFUSED` - the connection is refused.
             */
            seat(internal: AdHoc.Connection.Internal): Chain | undefined {
                this.secured = undefined;
                this._internal = internal;
                internal.External?.(this);
                const c = this.secured as Chain | undefined; //set by External( this ) meanwhile
                this.secured = undefined;
                return c === undefined || c === REFUSED || c.codec !== undefined ? c : undefined; //a chain with no pattern has nothing to apply
            }

            /** The protocol layer seated has no keys for the connection ( {@link secure} with `undefined` ). */
            static refused(): Error { return new Error("The protocol layer refused the connection: [Noise] of its description has no keys for it."); }

//#region Multiplexed port
            /** Listening side: the caller has not named its connection yet - its first byte will. */
            private muxPending = false;

            /** Dialing side: the byte naming the connection is still to go out, in front of everything else. */
            private muxOut = false;

            private readonly muxLead: AdHoc.BytesSrc = {
                read: (view, offset) => {
                    const id = this._internal?.id;
                    if (!Number.isInteger(id) || id! < 0 || id! > 255) throw new RangeError("Multiplexed Internal.id must be a byte");
                    view.setUint8(offset, id!);
                    this.muxOut = false;
                    return 1;
                },
                get isOpen() { return true; }, close() { },
            };

            /**
             * Where the received plaintext goes. Listening side of a multiplexed port: the first byte, in the clear, names the
             * connection; the Internal it names is seated - the bytes behind the byte are of the Noise it declares, this end
             * answers -, hears the connect and the open this connection took for it, and the rest of the bytes.
             */
            private readonly plain: AdHoc.BytesDst = {
                write: (view, offset, length) => {
                    let named = 0;
                    if (this.muxPending) {
                        if (length === 0) return 0;
                        this.muxPending = false;
                        const declared = this.seat((this.host as Server<AdHoc.Connection.Internal>).newInternal(this, view.getUint8(offset)));
                        offset++;
                        length--;
                        named = 1;
                        if (declared === REFUSED) { //no keys for the caller: closed
                            this.host.report(this, ExternalConnection.refused());
                            this.abort();
                            return named;
                        }
                        if (declared !== undefined) this.codec = this.noise(declared, false);
                        this.connectEvents(); //the connect that waited for the caller's name
                        if (!this.isActive()) return named;
                        const codec = this.codec;
                        if (codec !== undefined) { //the rest is of the Noise: it hands the plaintext back here
                            if (length === 0) return named;
                            const n = codec.write(view, offset, length);
                            return n < 0 ? n : n + named;
                        }
                    }
                    if (!this.isActive()) return -1;
                    const dst = this._internal?.BytesDst;
                    if (dst === undefined) return length + named;
                    const n = dst.write(view, offset, length);
                    return n < 0 ? n : n + named;
                },
                //a record in the clear of the Noise: frames of tunnels with a Noise of their own, for the Internal to take apart
                writeClear: (view, offset, length) => {
                    if (!this.isActive()) return -1;
                    const dst = this._internal?.BytesDst;
                    if (dst === undefined) return length;
                    return dst.writeClear ? dst.writeClear(view, offset, length) : -1;
                },
                get isOpen() { return true; },
                close() { },
            };
//#endregion

//#region Codec
            /** The encrypted stream between this connection and its Internal, one per socket; `undefined` - plain. */
            private codec?: Codec | undefined;

            /** The key of the other side, proved by the handshake of this socket: for a pattern that brings it. */
            get peerKey(): Uint8Array | undefined { return this.codec?.peerKey; }

            /** What the transport sends from: the byte naming the connection first, in the clear; then the codec, or the Internal. */
            protected TxSrc(): AdHoc.BytesSrc | undefined {
                return this.muxOut ? this.muxLead : this.codec ?? this._internal?.BytesSrc;
            }

            /** Where the received bytes go: the codec, or the Internal. */
            protected RxDst(): AdHoc.BytesDst { return this.codec ?? this.plain; }

            /** This end writes the first message of the handshake: the one that dialed. A data channel of WebRTC - its offerer. */
            protected get initiator(): boolean { return this.client; }

            /** The Noise stream of `declared` between this connection and its Internal, for a new socket: `initiator` writes the first message. */
            private noise(declared: Chain, initiator: boolean): Codec {
                return declared.codec!({
                    role: initiator ? "client" : "server",
                    source: () => this._internal?.BytesSrc,
                    destination: () => this.plain,
                    wake: () => this.WakeTransmit(),
                });
            }
