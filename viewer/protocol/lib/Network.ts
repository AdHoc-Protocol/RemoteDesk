/**
 * The TCP transport of the Java runtime (org.unirail.Network), on the event loop of a JavaScript runtime.
 *
 * The structure, the names and the lifecycle are Java's: TCP / Engine / ExternalConnection / WebSocket / Server /
 * Client / Wire, a slot that goes FREE - ACTIVE - CLEANING - FREE or PARKED, `receiverConnected` /
 * `transmitterConnected`, the transmit runner, `disconnect` / `closeOnLoop`, `parkConnection` / `reapParked`.
 *
 * What is the runtime's and not Java's: there is one thread, so no locks, no inbox and no loop per connection; the
 * socket is a {@link Channel} the platform adapter supplies (a Node socket, a browser or Workers WebSocket); timers come
 * from an injectable {@link Scheduler}; RFC 6455 framing and the HTTP upgrade are done by the platform; the Noise of a
 * connection comes with the chain its protocol layer declares ( {@link TCP.ExternalConnection.secure} ), so importing this
 * module loads no cryptography. No DOM, Node or Cloudflare typings.
 */
