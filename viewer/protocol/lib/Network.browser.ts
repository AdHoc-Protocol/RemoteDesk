    /**
     * A `[Stream]` source that reads a WebSocket: every binary message arriving on `url` becomes bytes of the stream a
     * pack sends. It is the innermost stage (the leaf) of the stream: the `Chunked` framer the generated code wires around
     * it adds the `[len]` framing of each chunk and the `0x0000` terminator.
     *
     * The socket opens on the first {@link __get_bytes}, when the pack starts sending. Messages are queued as they arrive
     * and copied into the framer's window; a CLEAN close of the socket ends the stream once the queue is drained, and the
     * framer then writes the terminator. An unclean close is a failure ({@link onFailure}) - the stream does not end.
     * Text messages are ignored: only `ArrayBuffer`s are bytes ({@link https://developer.mozilla.org/en-US/docs/Web/API/WebSocket/binaryType binaryType}).
     *
     * ```ts
     * // wherever the generated API takes the source of a [Stream] field:
     * const feed = new Network.FromWebSocket( "wss://camera.local/feed" );
     * ```
     */
    export class FromWebSocket implements AdHoc.Connection.Transmitter.BytesSrc {
        private ws?: WebSocket | undefined;
        private opened: boolean = false;

        /** The WebSocket the bytes come from: `ws:` or `wss:`. */
        url: string | URL;

        /** Pack/dispatch id - unused by an inner leaf: the framer around it carries the pack's. */
        public __id = 0;

        // Messages not yet copied into the framer's window; _head is the read position in the first one.
        private _queue: Uint8Array[] = [];
        private _head = 0;
        private _eof = false; // a clean close: the stream ends once the queue is drained

        public constructor(url: string | URL) {
            this.url = url;
        }

        /**
         * Fills the framer's window `[dst.byte, dst.byte_max)` with queued bytes.
         * @return `true` when the stream is over: the socket closed cleanly and every byte went out; `false` - more is to come.
         */
        public __get_bytes(dst: AdHoc.Connection.Transmitter): boolean {
            if (!this.opened) {
                this.opened = true;
                this.ws = new WebSocket(this.url);
                this.ws.binaryType = "arraybuffer";
                this.ws.onopen = this.onopen;
                this.ws.onmessage = this.onmessage;
                this.ws.onclose = this.onclose;
            }

            // Copy queued message bytes into the (framer-clamped) transmit window.
            while (dst.byte < dst.byte_max && 0 < this._queue.length) {
                const head = this._queue[0];
                const room = dst.byte_max - dst.byte;
                const avail = head.length - this._head;
                const n = avail < room ? avail : room;
                new Uint8Array(dst.buffer!.buffer, dst.buffer!.byteOffset + dst.byte, n).set(head.subarray(this._head, this._head + n));
                dst.byte += n;
                this._head += n;
                if (head.length <= this._head) {
                    this._queue.shift();
                    this._head = 0;
                }
            }

            // Done only when the source is closed AND everything queued has been produced;
            // otherwise park (buffer full with more queued, or queue momentarily empty).
            return this._eof && this._queue.length === 0;
        }

        private onopen = (): void => console.log("WebSocket connection established.");

        private onmessage = (event: MessageEvent): void => {
            if (event.data instanceof ArrayBuffer) this._queue.push(new Uint8Array(event.data));
            else console.warn("Received non-binary message, ignoring:", event.data);
        };

        private onclose = (event: CloseEvent): void => {
            console.log(`WebSocket connection closed. Code: ${event.code}, Clean: ${event.wasClean}`);
            if (event.wasClean) this._eof = true;
            else this.onFailure(new Error(`WebSocket closed unexpectedly. Code: ${event.code}`));
        };

        /**
         * The socket closed uncleanly ({@link https://developer.mozilla.org/en-US/docs/Web/API/CloseEvent/wasClean wasClean}
         * is false): the stream cannot end, the pack that carries it will not complete. The default logs it; override to
         * abort the connection or report to the user.
         */
        protected onFailure(error: Error): void {
            console.error("FromWebSocket stream failed:", error);
        }

        /** Closes the socket: a clean close, so the stream ends once what is queued has gone out. */
        public closeConnection(): void {
            if (this.ws && this.ws.readyState < WebSocket.CLOSING) this.ws.close();
        }
    }

    /**
     * A `[Stream]` destination that writes a WebSocket: the bytes of a stream a pack receives go out as binary messages
     * on `url`. It is the innermost stage (the leaf) of the stream: the `Chunked` framer the generated code wires around
     * it strips the framing and hands it payload only.
     *
     * The socket opens on the first {@link __put_bytes}, when the stream starts arriving; what arrives while it is
     * connecting is kept and sent once it opens. Every chunk is copied out - the receive window is not the leaf's to
     * keep - and the leaf never ends the stream itself: the framer's terminator does. A socket error, or a close the
     * leaf did not expect, is a failure ({@link onFailure}): the socket is closed with code 3002 and the rest is dropped.
     *
     * ```ts
     * // wherever the generated API takes the destination of a received [Stream] field:
     * const upload = new Network.ToWebSocket( "wss://archive.local/upload" );
     * ```
     */
    export class ToWebSocket implements AdHoc.Connection.Receiver.BytesDst {
        private ws: WebSocket | null = null;
        private opened: boolean = false;
        private sendBuffer: ArrayBuffer[] = [];
        private hasFailedOrCompleted: boolean = false;
        private readonly url: string | URL;

        /** Pack/dispatch id - unused by an inner leaf: the framer around it carries the pack's. */
        public __id = 0;

        /** @param url The WebSocket the bytes go to: `ws:` or `wss:`. */
        public constructor(url: string | URL) {
            this.url = url;
        }

        /**
         * Sends the framer's window `[src.byte, src.byte_max)` - copied, since the window is not this leaf's - and
         * consumes it.
         * @return always `false`: a leaf never ends the stream, the framer's terminator does.
         */
        public __put_bytes(src: AdHoc.Connection.Receiver): boolean {
            if (!this.opened) {
                this.opened = true;
                this.openWebSocket();
            }

            const len = src.byte_max - src.byte;
            if (0 < len) {
                if (!this.hasFailedOrCompleted && this.ws) {
                    // Copy out - the source buffer is foreign-owned and not safe to retain.
                    const copy = new ArrayBuffer(len);
                    new Uint8Array(copy).set(new Uint8Array(src.buffer!.buffer, src.buffer!.byteOffset + src.byte, len));
                    if (this.ws.readyState === WebSocket.OPEN) this.ws.send(copy);
                    else if (this.ws.readyState === WebSocket.CONNECTING) this.sendBuffer.push(copy);
                    else this.onFailure(new Error("Cannot send data: WebSocket is not open."));
                }
                src.byte += len;
            }
            return false;
        }

        /** Opens the socket and wires its handlers; a constructor that throws (a bad URL) is a failure on the next turn. */
        private openWebSocket(): void {
            try {
                this.ws = new WebSocket(this.url);
                this.ws.binaryType = "arraybuffer";

                this.ws.onopen = () => {
                    console.log(`WebSocket connection to ${this.url} established.`);
                    this.flushBuffer();
                };

                this.ws.onerror = () => this.onFailure(new Error("WebSocket connection error."));

                this.ws.onclose = (event) => {
                    if (!this.hasFailedOrCompleted) this.onFailure(new Error(`WebSocket closed unexpectedly. Code: ${event.code}, Reason: ${event.reason}`));
                };
            } catch (error) {
                setTimeout(() => this.onFailure(error as Error), 0);
            }
        }

        /** Sends what arrived while the socket was connecting. */
        private flushBuffer(): void {
            if (!this.ws) return;
            for (const chunk of this.sendBuffer) this.ws.send(chunk);
            this.sendBuffer = [];
        }

        /**
         * The socket failed or closed unexpectedly: it is closed with code 3002 - the application range a page may use,
         * https://developer.mozilla.org/en-US/docs/Web/API/WebSocket/close - and nothing more is sent. Once only. An
         * override that adds its own handling calls `super.onFailure( reason )`.
         */
        protected onFailure(reason: Error): void {
            if (this.hasFailedOrCompleted) return;
            this.hasFailedOrCompleted = true;
            console.error("Stream failed. Terminating WebSocket connection.", reason);
            if (this.ws) {
                this.ws.onclose = null; // Prevent onclose from firing another failure
                this.ws.onerror = null;
                this.ws.close(3002, "Stream error");
            }
        }
    }

    /**
     * A page's connection to a WebSocket server: the browser's `WebSocket` under the shared
     * {@link Core.TCP.WebSocket.Client}. The session - its lifecycle, timers, resumable identity and the closing
     * handshake - is the core's, the one every runtime has; this class keeps the API and the behaviour the TypeScript
     * client always had:
     *
     * - {@link connect} retries: {@link maxRetries} more attempts after the first, the wait doubling from
     *   {@link retryDelay} (1 s, 2 s, 4 s). Every failure goes to `onFailure`; after the last the promise resolves with
     *   `undefined` instead of rejecting.
     * - `toString()` is `name:state` - `name:wss://…` while connected, `name:connecting`, `name:failed`, `name:closed`.
     * - It is itself the `External` of the connection: identity, timeouts and the wakes pass through to the core.
     *
     * ```ts
     * const client = new Network.WebSocketClient( "dashboard", ext => new Channel(), ( source, error ) => console.error( source, error ) );
     * client.maxRetries = 5;
     * const channel = await client.connect( "wss://my.server/channel" );
     * if( !channel ) showOffline();
     * ```
     *
     * A multiplexed server port (`mux`): every socket opens with one byte - the `id` of the connection's Internal - that
     * names the connection the server seats on it.
     *
     * Behind it: the WebSocket API https://developer.mozilla.org/en-US/docs/Web/API/WebSocket.
     */
