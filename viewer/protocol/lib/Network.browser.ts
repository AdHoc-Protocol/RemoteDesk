/**
 * @module Network.browser
 * AdHoc connections in a web page: the WebSocket client, WebSocket stream leaves, and peer-to-peer WebRTC.
 *
 * Everything that is not the browser's lives in `Network.ts` and is re-exported from here unchanged ({@link TCP},
 * {@link Wire}, {@link Loopback}, {@link Host}), so a page imports only this module. What this module adds:
 *
 * - {@link WebSocketClient} - a page connecting to a server: the browser's `WebSocket` under the shared
 *   `TCP.WebSocket.Client`, with retries, end-to-end encryption by [Noise] and multiplexed ports.
 * - {@link FromWebSocket} / {@link ToWebSocket} - stream leaves: bytes of a WebSocket as a `[Stream]` field of a pack.
 * - {@link WebRTCClient} - a direct data channel between two pages, negotiated through a signaling WebSocket.
 *
 * ## A page connects
 * ```ts
 * import Network from "./lib/Network.browser";
 * import Channel from "./gen/MyChannel/Connection";
 *
 * const client  = new Network.WebSocketClient( "my page", ext => new Channel() );
 * const channel = await client.connect( "wss://my.server/channel" );   // undefined after the last failed retry
 * if( channel ) {
 *     // send packs through the generated API of `channel`; replies arrive in its handlers
 * }
 * client.closeGracefully( 1000, "Bye" );                             // the WebSocket closing handshake
 * ```
 *
 * Encrypted end to end (Noise: X25519, then ChaCha20-Poly1305) when [Noise] of the description of the protocol says so: the
 * keys come from the region "The keys of Noise" of the generated connection, who is let in from "The key the far end
 * proved". The cipher's WebAssembly is compiled asynchronously before the first socket - a browser may refuse a synchronous
 * compile on its main thread. TLS is the browser's: a `wss:` URL.
 *
 * ## Where it runs
 * The module type-checks in any project - a Node test host, a Cloudflare Worker - because the browser API it uses is
 * declared below structurally. It RUNS where those globals are: `WebSocket` is in every browser, in Node 22+ and in
 * Workers; `RTCPeerConnection` only in browsers.
 *
 * ## Official sources
 * - The WebSocket API: https://developer.mozilla.org/en-US/docs/Web/API/WebSocket
 *   and its standard: https://websockets.spec.whatwg.org/
 * - Close codes a page may use (1000, 3000-4999) and the 123-byte reason: https://developer.mozilla.org/en-US/docs/Web/API/WebSocket/close
 * - `binaryType` ("arraybuffer"): https://developer.mozilla.org/en-US/docs/Web/API/WebSocket/binaryType
 * - `CloseEvent` (`code`, `reason`, `wasClean`): https://developer.mozilla.org/en-US/docs/Web/API/CloseEvent
 * - The WebSocket protocol: https://www.rfc-editor.org/rfc/rfc6455
 * - WebRTC: https://developer.mozilla.org/en-US/docs/Web/API/RTCPeerConnection,
 *   https://developer.mozilla.org/en-US/docs/Web/API/RTCDataChannel and the specification https://www.w3.org/TR/webrtc/
 * - Signaling - exchanging SDP and ICE candidates through a server: https://developer.mozilla.org/en-US/docs/Web/API/WebRTC_API/Signaling_and_video_calling
 * - Offer collisions ("glare"): https://developer.mozilla.org/en-US/docs/Web/API/WebRTC_API/Perfect_negotiation
 */
